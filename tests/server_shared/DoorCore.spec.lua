--!strict
local Harness = require("../Harness")
local DoorCore = require("../../src/server_shared/Door/DoorCore")

local test, expectTrue, expectFalse, expectEqual, expectError = Harness.test, Harness.expectTrue, Harness.expectFalse, Harness.expectEqual, Harness.expectError

local States = DoorCore.States
local Reasons = DoorCore.Reasons

local function newDoor(initialState: string?, transitionSeconds: number?): any
    return DoorCore.new({ initialState = initialState or States.Closed, transitionSeconds = transitionSeconds or 0.6 })
end

test("a new door starts in its configured state and is not transitioning", function()
    local closed = newDoor()
    expectEqual(closed:getState(), "Closed")
    expectFalse(closed:isTransitioning(0))
    expectEqual(closed:getTransitionEndsAt(), nil)
    expectEqual(newDoor(States.Open):getState(), "Open")
end)

test("nextState is the opposite state and does not mutate", function()
    local door = newDoor()
    expectEqual(door:nextState(), "Open")
    expectEqual(door:getState(), "Closed")
    expectEqual(newDoor(States.Open):nextState(), "Closed")
end)

test("planToggle is non-mutating and reports the state a toggle would produce", function()
    local door = newDoor()
    local target, reason = door:planToggle(10)
    expectEqual(target, "Open")
    expectEqual(reason, nil)
    expectEqual(door:getState(), "Closed", "planning changed nothing")
    expectEqual(door:getTransitionEndsAt(), nil)
end)

test("Closed -> Open", function()
    local door = newDoor()
    local ok, reason = door:commitToggle("Open", 10)
    expectTrue(ok)
    expectEqual(reason, nil)
    expectEqual(door:getState(), "Open")
    expectEqual(door:getTransitionEndsAt(), 10.6)
end)

test("Open -> Closed", function()
    local door = newDoor(States.Open)
    local ok = door:commitToggle("Closed", 10)
    expectTrue(ok)
    expectEqual(door:getState(), "Closed")
end)

test("a full open/close cycle after the transition window", function()
    local door = newDoor(States.Closed, 1)
    expectTrue((door:commitToggle("Open", 0)))
    expectTrue((door:commitToggle("Closed", 1)), "exactly at the deadline the door is toggleable again")
    expectEqual(door:getState(), "Closed")
    expectTrue((door:commitToggle("Open", 5)))
    expectEqual(door:getState(), "Open")
end)

test("a toggle is rejected while the door is transitioning and leaves the state unchanged", function()
    local door = newDoor(States.Closed, 1)
    expectTrue((door:commitToggle("Open", 10)))
    local target, reason = door:planToggle(10.5)
    expectEqual(target, nil)
    expectEqual(reason, Reasons.TRANSITIONING)
    local ok, commitReason = door:commitToggle("Closed", 10.5)
    expectFalse(ok)
    expectEqual(commitReason, Reasons.TRANSITIONING)
    expectEqual(door:getState(), "Open", "state unchanged after the rejection")
    expectEqual(door:getTransitionEndsAt(), 11, "deadline unchanged after the rejection")
    expectTrue(door:isTransitioning(10.999))
    expectFalse(door:isTransitioning(11))
end)

test("an invalid transition is rejected and leaves the door unchanged", function()
    local door = newDoor()
    local ok, reason = door:commitToggle("Closed", 10) -- Closed -> Closed is not a toggle
    expectFalse(ok)
    expectEqual(reason, Reasons.INVALID_TRANSITION)
    expectEqual(door:getState(), "Closed")
    expectEqual(door:getTransitionEndsAt(), nil)
    for _, bad in ipairs({ "Ajar", "open", "", 1, true }) do
        local badOk, badReason = door:commitToggle(bad, 10)
        expectFalse(badOk, tostring(bad))
        expectEqual(badReason, Reasons.INVALID_STATE, tostring(bad))
    end
    local nilOk, nilReason = door:commitToggle(nil, 10)
    expectFalse(nilOk)
    expectEqual(nilReason, Reasons.INVALID_STATE)
    expectEqual(door:getState(), "Closed")
end)

test("an invalid clock value fails closed and changes nothing", function()
    local door = newDoor()
    for _, now in ipairs({ 0 / 0, math.huge, -math.huge, "10", true }) do
        expectTrue(door:isTransitioning(now), "invalid time counts as transitioning: " .. tostring(now))
        local target, reason = door:planToggle(now)
        expectEqual(target, nil)
        expectEqual(reason, Reasons.INVALID_TIME)
        local ok, commitReason = door:commitToggle("Open", now)
        expectFalse(ok)
        expectEqual(commitReason, Reasons.INVALID_TIME)
    end
    local nilTarget, nilReason = door:planToggle(nil)
    expectEqual(nilTarget, nil)
    expectEqual(nilReason, Reasons.INVALID_TIME)
    expectEqual(door:getState(), "Closed")
    expectEqual(door:getTransitionEndsAt(), nil)
end)

test("a backward clock can only extend a transition, never end it early", function()
    local door = newDoor(States.Closed, 1)
    expectTrue((door:commitToggle("Open", 100)))
    expectTrue(door:isTransitioning(50))
    expectTrue(door:isTransitioning(-1000))
    local ok = door:commitToggle("Closed", 50)
    expectFalse(ok)
    expectEqual(door:getState(), "Open")
end)

test("a door can never be permanently stuck: time alone ends the transition", function()
    local door = newDoor(States.Closed, 10)
    expectTrue((door:commitToggle("Open", 0)))
    expectTrue(door:isTransitioning(9.99))
    expectFalse(door:isTransitioning(10))
    expectFalse(door:isTransitioning(1e9))
    expectTrue((door:commitToggle("Closed", 1e9)))
end)

test("two sequential toggles at the same instant: only the first succeeds", function()
    local door = newDoor()
    expectTrue((door:commitToggle("Open", 5)))
    local ok, reason = door:commitToggle("Closed", 5)
    expectFalse(ok)
    expectEqual(reason, Reasons.TRANSITIONING)
    expectEqual(door:getState(), "Open")
end)

test("validateConfig accepts valid and rejects invalid configurations", function()
    expectTrue((DoorCore.validateConfig({ initialState = "Closed", transitionSeconds = 0.6 })))
    expectTrue((DoorCore.validateConfig({ initialState = "Open", transitionSeconds = 0.1 })))
    expectTrue((DoorCore.validateConfig({ initialState = "Open", transitionSeconds = 10 })))
    local function invalid(config: any, label: string)
        local ok, detail = DoorCore.validateConfig(config)
        expectFalse(ok, label)
        expectTrue(type(detail) == "string", label)
    end
    invalid(nil, "nil")
    invalid("config", "string")
    invalid(setmetatable({ initialState = "Closed", transitionSeconds = 1 }, {}), "metatable")
    invalid({ initialState = "Ajar", transitionSeconds = 1 }, "bad state")
    invalid({ transitionSeconds = 1 }, "missing state")
    invalid({ initialState = "Closed" }, "missing seconds")
    invalid({ initialState = "Closed", transitionSeconds = 1, extra = true }, "unknown field")
    for _, seconds in ipairs({ 0, 0.099, 10.001, -1, 0 / 0, math.huge, -math.huge, "1", true }) do
        invalid({ initialState = "Closed", transitionSeconds = seconds }, "seconds " .. tostring(seconds))
    end
end)

test("new raises on an invalid configuration", function()
    expectError(function()
        DoorCore.new({ initialState = "Ajar", transitionSeconds = 1 } :: any)
    end, "bad state")
    expectError(function()
        DoorCore.new({ initialState = "Closed", transitionSeconds = 0 } :: any)
    end, "bad seconds")
end)

test("states, limits and reasons are frozen", function()
    expectTrue(table.isfrozen(DoorCore.States))
    expectTrue(table.isfrozen(DoorCore.Limits))
    expectTrue(table.isfrozen(DoorCore.Reasons))
end)

test("independent doors do not share state", function()
    local a, b = newDoor(), newDoor()
    expectTrue((a:commitToggle("Open", 0)))
    expectEqual(a:getState(), "Open")
    expectEqual(b:getState(), "Closed")
    expectEqual(b:getTransitionEndsAt(), nil)
end)
